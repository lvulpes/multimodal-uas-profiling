log = logging.getLogger("sitl")


class TestFailure(RuntimeError):
    """A pass criterion was not met."""


def load_yaml(path: Path) -> dict[str, Any]:
    with path.open() as f:
        return yaml.safe_load(f)


def load_profile(name: str) -> dict[str, Any]:
    return load_yaml(REPO / "profiles" / f"{name}.yaml")


def make_log_dir(cfg: dict[str, Any], test: str, profile: str) -> Path:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    path = REPO / cfg["log_root"] / f"{test}-{profile}-{stamp}"
    path.mkdir(parents=True)
    return path


def setup_logging(log_dir: Path) -> None:
    fmt = logging.Formatter("%(asctime)s %(levelname)s %(name)s: %(message)s")
    root = logging.getLogger()
    root.setLevel(logging.INFO)
    for handler in (logging.StreamHandler(), logging.FileHandler(log_dir / "test.log")):
        handler.setFormatter(fmt)
        root.addHandler(handler)


# ---------------------------------------------------------------- flight stacks


def launch_stack(profile: dict[str, Any], cfg: dict[str, Any], log_dir: Path) -> subprocess.Popen:
    stack = profile["flight"]["stack"]
    work = log_dir / "sitl"
    work.mkdir()
    out = (log_dir / "sitl.log").open("w")
    if stack == "px4":
        cmd, env = _px4_command(profile, cfg, work)
    elif stack == "ardupilot":
        cmd, env = _ardupilot_command(profile, cfg)
    else:
        raise ValueError(f"unknown stack {stack!r}")
    log.info("launch %s: %s", stack, " ".join(cmd))
    # Own session so teardown can kill the whole tree (PX4 starts gz sim as a child).
    return subprocess.Popen(
        cmd,
        cwd=work,
        env=env,
        stdin=subprocess.DEVNULL,
        stdout=out,
        stderr=subprocess.STDOUT,
        start_new_session=True,
    )


def _px4_command(
    profile: dict[str, Any], cfg: dict[str, Any], work: Path
) -> tuple[list[str], dict[str, str]]:
    build = Path(os.environ["PX4_ROOT"]) / "build" / "px4_sitl_default"
    sitl = profile["flight"]["sitl"]
    home = cfg["home"]
    env = dict(os.environ)
    env.update(
        PX4_SIM_MODEL=sitl["model"],
        PX4_GZ_WORLD=sitl["world"],
        PX4_HOME_LAT=str(home["lat"]),
        PX4_HOME_LON=str(home["lon"]),
        PX4_HOME_ALT=str(home["alt_m"]),
        GZ_IP=cfg["gazebo"]["ip"],
        GZ_PARTITION=work.parent.name,
    )
    if sitl.get("headless"):
        env["HEADLESS"] = "1"
    # gz_env.sh (generated by the build) sets the Gazebo model/world/plugin paths. px4-rc.gzsim only
    # looks for it next to the working directory, which is a fresh run dir here.
    script = (
        f'. "{build}/rootfs/gz_env.sh" && '
        f'exec "{build}/bin/px4" -d -w "{work / "rootfs"}" "{build}/etc"'
    )
    return ["bash", "-c", script], env


def _ardupilot_command(
    profile: dict[str, Any], cfg: dict[str, Any]
) -> tuple[list[str], dict[str, str]]:
    root = Path(os.environ["ARDUPILOT_ROOT"])
    sitl = profile["flight"]["sitl"]
    ports = cfg["stacks"]["ardupilot"]
    home = cfg["home"]
    cmd = [
        str(root / "build" / "sitl" / "bin" / "arducopter"),
        "--model",
        sitl["model"],
        "--speedup",
        "1",
        "--wipe",
        "--home",
        f"{home['lat']},{home['lon']},{home['alt_m']},0",
        "--defaults",
        str(root / sitl["defaults"]),
        "--serial0",
        f"udpclient:{LOCALHOST}:{ports['vehicle_port']}",
        "--serial1",
        f"udpclient:{LOCALHOST}:{ports['monitor_port']}",
    ]
    return cmd, dict(os.environ)


def stop_stack(proc: subprocess.Popen, timeout_s: float) -> None:
    if proc.poll() is not None:
        log.info("stack already exited with %s", proc.returncode)
    for sig in (signal.SIGINT, signal.SIGTERM, signal.SIGKILL):
        try:
            os.killpg(proc.pid, sig)
        except ProcessLookupError:
            return
        if proc.returncode is not None:
            continue  # leader gone; escalate to make sure its children (gz sim) are gone too
        try:
            proc.wait(timeout_s)
            break
        except subprocess.TimeoutExpired:
            continue
    # Children (gz sim) can outlive the leader; make sure the group is gone.
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass


# ---------------------------------------------------------------- C2 link stand-in


@dataclass
class RelayStats:
    up_fwd: int = 0  # GCS -> vehicle
    up_drop: int = 0
    down_fwd: int = 0  # vehicle -> GCS
    down_drop: int = 0


class UdpRelay(threading.Thread):
    """Forwards UDP datagrams between vehicle and GCS; `cut` drops both directions.

    Vehicle side: bound to vehicle_port, which the stack sends to; the stack's address is learned
    from its first datagram. GCS side: an ephemeral socket that sends to the GCS port.
    """

    def __init__(self, vehicle_port: int, gcs_port: int) -> None:
        super().__init__(daemon=True, name="relay")
        self.cut = threading.Event()
        self.stats = RelayStats()
        self._halt = threading.Event()
        self._vehicle = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self._vehicle.bind((LOCALHOST, vehicle_port))
        self._gcs = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self._gcs.bind((LOCALHOST, 0))
        self._gcs_addr = (LOCALHOST, gcs_port)
        self._vehicle_addr: tuple[str, int] | None = None

    def run(self) -> None:
        socks = [self._vehicle, self._gcs]
        while not self._halt.is_set():
            ready, _, _ = select.select(socks, [], [], 0.2)
            for sock in ready:
                data, addr = sock.recvfrom(65535)
                cut = self.cut.is_set()
                if sock is self._vehicle:
                    self._vehicle_addr = addr
                    if cut:
                        self.stats.down_drop += 1
                    else:
                        self._gcs.sendto(data, self._gcs_addr)
                        self.stats.down_fwd += 1
                elif cut or self._vehicle_addr is None:
                    self.stats.up_drop += 1
                else:
                    self._vehicle.sendto(data, self._vehicle_addr)
                    self.stats.up_fwd += 1

    def stop(self) -> None:
        self._halt.set()
        self.join(2)
        self._vehicle.close()
        self._gcs.close()


# ---------------------------------------------------------------- GCS


def mode_of(hb: Any) -> str:
    return mavutil.mode_string_v10(hb)


def is_armed(hb: Any) -> bool:
    return bool(hb.base_mode & mavutil.mavlink.MAV_MODE_FLAG_SAFETY_ARMED)


def is_vehicle_heartbeat(msg: Any, sysid: int) -> bool:
    return (
        msg.get_type() == "HEARTBEAT"
        and msg.get_srcSystem() == sysid
        and msg.get_srcComponent() == mavutil.mavlink.MAV_COMP_ID_AUTOPILOT1
        and msg.type != mavutil.mavlink.MAV_TYPE_GCS
    )


@dataclass
class VehicleState:
    heartbeat: Any = None
    position: Any = None
    statustext: list[str] = field(default_factory=list)


class Gcs:
    """pymavlink ground station: sends heartbeats, tracks vehicle state, issues commands."""

    def __init__(self, cfg: dict[str, Any], stack: str, sysid: int) -> None:
        gcs = cfg["gcs"]
        self.cfg = cfg
        self.stack = stack
        self.sysid = sysid
        self.conn = mavutil.mavlink_connection(
            f"udpin:{LOCALHOST}:{gcs['port']}",
            source_system=gcs["system_id"],
            source_component=gcs["component_id"],
        )
        self.state = VehicleState()
        self._send_lock = threading.Lock()
        self._halt = threading.Event()
        self._hb_period = 1.0 / gcs["heartbeat_hz"]
        self._hb_thread = threading.Thread(target=self._heartbeats, daemon=True, name="gcs-hb")
        self._hb_thread.start()

    def _heartbeats(self) -> None:
        while not self._halt.wait(self._hb_period):
            with self._send_lock:
                self.conn.mav.heartbeat_send(
                    mavutil.mavlink.MAV_TYPE_GCS,
                    mavutil.mavlink.MAV_AUTOPILOT_INVALID,
                    0,
                    0,
                    mavutil.mavlink.MAV_STATE_ACTIVE,
                )

    def close(self) -> None:
        self._halt.set()
        self._hb_thread.join(2)
        self.conn.close()

    # -- receiving

    def poll(self, timeout_s: float) -> Any:
        msg = self.conn.recv_match(blocking=True, timeout=timeout_s)
        if msg is None or msg.get_srcSystem() != self.sysid:
            return msg
        kind = msg.get_type()
        if is_vehicle_heartbeat(msg, self.sysid):
            self.state.heartbeat = msg
        elif kind == "GLOBAL_POSITION_INT":
            self.state.position = msg
        elif kind == "STATUSTEXT":
            self.state.statustext.append(msg.text)
            log.info("vehicle: %s", msg.text)
        return msg

    def wait_for(self, what: str, cond: Any, timeout_s: float) -> None:
        deadline = time.monotonic() + timeout_s
        while time.monotonic() < deadline:
            self.poll(min(0.5, max(0.0, deadline - time.monotonic())))
            if cond():
                return
        raise TestFailure(f"timeout after {timeout_s:.0f} s waiting for {what}")

    def wait_heartbeat(self, timeout_s: float) -> Any:
        self.wait_for("vehicle heartbeat", lambda: self.state.heartbeat is not None, timeout_s)
        hb = self.state.heartbeat
        self.conn.target_system = self.sysid
        self.conn.target_component = mavutil.mavlink.MAV_COMP_ID_AUTOPILOT1
        return hb

    # -- commands

    def command_long(self, command: int, *params: float) -> int:
        """Send COMMAND_LONG and return the COMMAND_ACK result."""
        p = list(params) + [0.0] * (7 - len(params))
        with self._send_lock:
            self.conn.mav.command_long_send(self.sysid, 1, command, 0, *p)
        deadline = time.monotonic() + self.cfg["timeouts_s"]["param"]
        while time.monotonic() < deadline:
            msg = self.poll(0.5)
            if msg is not None and msg.get_type() == "COMMAND_ACK" and msg.command == command:
                return msg.result
        return -1

    def request_position(self) -> None:
        interval_us = 1e6 / self.cfg["position_rate_hz"]
        result = self.command_long(
            mavutil.mavlink.MAV_CMD_SET_MESSAGE_INTERVAL,
            mavutil.mavlink.MAVLINK_MSG_ID_GLOBAL_POSITION_INT,
            interval_us,
        )
        if result != mavutil.mavlink.MAV_RESULT_ACCEPTED:
            raise TestFailure(f"SET_MESSAGE_INTERVAL rejected: result {result}")
        self.wait_for("GLOBAL_POSITION_INT", lambda: self.state.position is not None, 10)

    def set_params(self, params: dict[str, float]) -> dict[str, float]:
        """Set native params and read each back. Returns the confirmed values."""
        confirmed = {}
        for name, value in params.items():
            ptype = self._read_param(name)[1]
            with self._send_lock:
                self.conn.mav.param_set_send(
                    self.sysid, 1, name.encode(), self._encode(value, ptype), ptype
                )
            got = self._read_param(name)[0]
            if not math.isclose(got, float(value), rel_tol=1e-6):
                raise TestFailure(f"param {name}: set {value}, read back {got}")
            confirmed[name] = got
            log.info("param %s = %s", name, got)
        return confirmed

    def _read_param(self, name: str) -> tuple[float, int]:
        with self._send_lock:
            self.conn.mav.param_request_read_send(self.sysid, 1, name.encode(), -1)
        deadline = time.monotonic() + self.cfg["timeouts_s"]["param"]
        while time.monotonic() < deadline:
            msg = self.poll(0.5)
            if msg is not None and msg.get_type() == "PARAM_VALUE" and msg.param_id == name:
                return self._decode(msg.param_value, msg.param_type), msg.param_type
        raise TestFailure(f"no PARAM_VALUE for {name}")

    # PX4 encodes integer params bytewise in the float field; ArduPilot casts them.
    _INT_TYPES = {
        mavutil.mavlink.MAV_PARAM_TYPE_INT8: "b",
        mavutil.mavlink.MAV_PARAM_TYPE_UINT8: "B",
        mavutil.mavlink.MAV_PARAM_TYPE_INT16: "h",
        mavutil.mavlink.MAV_PARAM_TYPE_UINT16: "H",
        mavutil.mavlink.MAV_PARAM_TYPE_INT32: "i",
        mavutil.mavlink.MAV_PARAM_TYPE_UINT32: "I",
    }

    def _encode(self, value: float, ptype: int) -> float:
        if self.stack == "px4" and ptype in self._INT_TYPES:
            raw = struct.pack(f"<{self._INT_TYPES[ptype]}", int(value)).ljust(4, b"\0")
            return struct.unpack("<f", raw)[0]
        return float(value)

    def _decode(self, value: float, ptype: int) -> float:
        if self.stack == "px4" and ptype in self._INT_TYPES:
            fmt = self._INT_TYPES[ptype]
            raw = struct.pack("<f", value)[: struct.calcsize(fmt)]
            return float(struct.unpack(f"<{fmt}", raw)[0])
        return float(value)

    def arm_and_takeoff(self, alt_m: float) -> None:
        timeouts = self.cfg["timeouts_s"]
        # Pre-arm checks pass only once the estimator has converged; retry until then.
        # ArduPilot: GUIDED is (re)asserted every attempt because the SITL RC flight-mode channel
        # resets the mode to STABILIZE once RC input initialises during startup.
        deadline = time.monotonic() + timeouts["ready_to_arm"]
        while not (is_armed(self.state.heartbeat) and self._takeoff_mode_ok()):
            if time.monotonic() > deadline:
                raise TestFailure(
                    "vehicle did not arm in a takeoff-capable mode "
                    f"(mode {mode_of(self.state.heartbeat)})"
                )
            if not self._takeoff_mode_ok():
                self.command_long(
                    mavutil.mavlink.MAV_CMD_DO_SET_MODE,
                    mavutil.mavlink.MAV_MODE_FLAG_CUSTOM_MODE_ENABLED,
                    self.conn.mode_mapping()["GUIDED"],
                )
                self.wait_for_quietly(self._takeoff_mode_ok, 2.0)
            if self._takeoff_mode_ok() and not is_armed(self.state.heartbeat):
                self.command_long(mavutil.mavlink.MAV_CMD_COMPONENT_ARM_DISARM, 1)
                self.wait_for_quietly(lambda: is_armed(self.state.heartbeat), 2.0)
        log.info("armed")

        # MAV_CMD_NAV_TAKEOFF param7: PX4 takes AMSL altitude, ArduPilot relative altitude.
        if self.stack == "px4":
            target = self.state.position.alt / 1000.0 + alt_m
            result = self.command_long(
                mavutil.mavlink.MAV_CMD_NAV_TAKEOFF, -1, 0, 0, math.nan, math.nan, math.nan, target
            )
        else:
            result = self.command_long(mavutil.mavlink.MAV_CMD_NAV_TAKEOFF, 0, 0, 0, 0, 0, 0, alt_m)
        if result != mavutil.mavlink.MAV_RESULT_ACCEPTED:
            raise TestFailure(
                f"takeoff rejected: result {result} in mode {mode_of(self.state.heartbeat)}, "
                f"armed={is_armed(self.state.heartbeat)}"
            )
        reach = alt_m * self.cfg["takeoff_reached_fraction"]
        self.wait_for(
            f"relative altitude >= {reach:.1f} m",
            lambda: self.state.position.relative_alt / 1000.0 >= reach,
            timeouts["takeoff"],
        )
        log.info("takeoff reached %.1f m", self.state.position.relative_alt / 1000.0)

    def _takeoff_mode_ok(self) -> bool:
        """PX4 takes off from any mode via NAV_TAKEOFF; ArduCopter needs GUIDED."""
        return self.stack != "ardupilot" or mode_of(self.state.heartbeat) == "GUIDED"

    def wait_for_quietly(self, cond: Any, timeout_s: float) -> bool:
        try:
            self.wait_for("", cond, timeout_s)
            return True
        except TestFailure:
            return False


class Monitor(threading.Thread):
    """Passive listener on a second vehicle link: records mode changes, never sends."""

    def __init__(self, port: int, sysid: int) -> None:
        super().__init__(daemon=True, name="monitor")
        self.conn = mavutil.mavlink_connection(f"udpin:{LOCALHOST}:{port}")
        self.sysid = sysid
        self.mode_changes: list[tuple[float, str]] = []  # (wall-clock time, mode)
        self._halt = threading.Event()

    def run(self) -> None:
        while not self._halt.is_set():
            msg = self.conn.recv_match(type="HEARTBEAT", blocking=True, timeout=0.5)
            if msg is None or not is_vehicle_heartbeat(msg, self.sysid):
                continue
            mode = mode_of(msg)
            if not self.mode_changes or self.mode_changes[-1][1] != mode:
                self.mode_changes.append((time.time(), mode))
                log.info("monitor: mode %s", mode)

    def stop(self) -> None:
        self._halt.set()
        self.join(2)
        self.conn.close()


def write_summary(log_dir: Path, summary: dict[str, Any]) -> None:
    (log_dir / "summary.json").write_text(json.dumps(summary, indent=2, default=str) + "\n")


@dataclass
class Session:
    cfg: dict[str, Any]
    profile: dict[str, Any]
    log_dir: Path
    gcs: Gcs
    relay: UdpRelay
    monitor: Monitor
    summary: dict[str, Any]


def run_test(test: str, body: Any) -> int:
    """Parse --profile, start stack + relay + monitor + GCS, run body(session), tear down.

    Exit code: 0 = all pass criteria met, 1 = a criterion failed, 2 = harness error.
    """
    import argparse

    parser = argparse.ArgumentParser(description=f"stage-1 {test} test")
    parser.add_argument("--profile", required=True, help="profile name under profiles/")
    args = parser.parse_args()

    cfg = load_yaml(CONFIG)
    profile = load_profile(args.profile)
    stack = profile["flight"]["stack"]
    ports = cfg["stacks"][stack]
    log_dir = make_log_dir(cfg, test, args.profile)
    setup_logging(log_dir)
    summary: dict[str, Any] = {
        "test": test,
        "profile": args.profile,
        "stack": stack,
        "version": profile["flight"]["version"],
        "started": datetime.now(timezone.utc),
        "checks": {},
    }

    relay = UdpRelay(ports["vehicle_port"], cfg["gcs"]["port"])
    relay.start()
    monitor = Monitor(ports["monitor_port"], ports["vehicle_sysid"])
    monitor.start()
    gcs = Gcs(cfg, stack, ports["vehicle_sysid"])
    proc = launch_stack(profile, cfg, log_dir)
    code = 2
    try:
        body(Session(cfg, profile, log_dir, gcs, relay, monitor, summary))
        code = 0
    except TestFailure as exc:
        log.error("FAIL: %s", exc)
        summary["failure"] = str(exc)
        code = 1
    except Exception as exc:
        log.exception("harness error")
        summary["error"] = repr(exc)
    finally:
        if proc.poll() is not None:
            log.error("stack exited early with %s (see sitl.log)", proc.returncode)
        stop_stack(proc, cfg["timeouts_s"]["shutdown"])
        gcs.close()
        monitor.stop()
        relay.stop()
        summary.update(
            result={0: "PASS", 1: "FAIL"}.get(code, "ERROR"),
            relay=relay.stats.__dict__,
            mode_changes=monitor.mode_changes,
            statustext=gcs.state.statustext[-50:],
            log_dir=log_dir,
        )
        write_summary(log_dir, summary)
        log.info("%s %s: %s (logs: %s)", test, profile["name"], summary["result"], log_dir)
    return code


def connect_and_fly(s: Session) -> None:
    """Shared pass criteria: heartbeat, failsafe params confirmed, arm, takeoff."""
    t = s.cfg["timeouts_s"]
    hb = s.gcs.wait_heartbeat(t["heartbeat"])
    s.summary["checks"]["heartbeat"] = {"autopilot": hb.autopilot, "mode": mode_of(hb)}
    log.info("heartbeat: autopilot=%s mode=%s", hb.autopilot, mode_of(hb))
    native = {**s.profile["failsafe"]["native"], **s.profile["flight"]["params"]}
    s.summary["checks"]["params"] = s.gcs.set_params(native)
    s.gcs.request_position()
    s.gcs.arm_and_takeoff(s.cfg["takeoff_alt_m"])
    s.summary["checks"]["arm"] = True
    s.summary["checks"]["takeoff_alt_m"] = s.gcs.state.position.relative_alt / 1000.0
